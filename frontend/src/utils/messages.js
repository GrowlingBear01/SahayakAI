export function t(key, lang) {
  const item = copy[key];
  if (!item) return key;
  if (typeof item === "string") return item;
  return pickLang(item, lang);
}

export function pickLang(pair, lang) {
  if (!pair || typeof pair !== "object") return "";
  return resolvedLang(lang) === "hi" ? pair.hi || pair.en : pair.en || pair.hi;
}

export function resolvedLang(lang) {
  if (lang === "hi" || lang === "en") return lang;
  return browserPrefersHindi() ? "hi" : "en";
}

export function browserPrefersHindi() {
  const nav = String(
    (typeof navigator !== "undefined" && (navigator.language || navigator.userLanguage)) || "en",
  ).toLowerCase();
  return nav.startsWith("hi");
}

export function recognitionLocale(lang) {
  return resolvedLang(lang) === "hi" ? "hi-IN" : "en-IN";
}

export function recognitionErrorKey(error) {
  switch (error) {
    case "not-allowed":
    case "service-not-allowed":
      return "micDenied";
    case "no-speech":
      return "micNoSpeech";
    case "network":
      return "micNetworkError";
    case "audio-capture":
      return "micCaptureError";
    case "aborted":
      return null;
    default:
      return "micRecognitionError";
  }
}

export function eventMessage(event, lang) {
  if (!event) return "";
  return resolvedLang(lang) === "hi"
    ? event.message_hi || event.message_en || ""
    : event.message_en || event.message_hi || "";
}

export function isStopCommand(text) {
  const value = String(text || "")
    .trim()
    .toLowerCase();
  if (!value) return false;
  const commands = ["stop", "ruko", "ruk jao", "ruk ja", "रुक", "रुको", "रुक जाओ", "रुक जा"];
  return commands.some((cmd) => value === cmd || value.startsWith(`${cmd} `));
}

export const TERMINAL_STATES = new Set([
  "done",
  "could_not_finish",
  "stopped",
  "outcome_unknown",
]);

export const ACTIVE_TASK_STATES = new Set([
  "planning",
  "needs_info",
  "working",
  "waiting_for_approval",
  "submitting",
]);

export function isActiveTask(state) {
  return ACTIVE_TASK_STATES.has(state);
}
